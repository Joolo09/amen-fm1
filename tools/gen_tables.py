"""Fixed-point tables for building and testing the AMEN-FM1 engines on a desktop.

Writes the same tables a Felucca host gives its plugins (SINE, PITCH_OCT / pitch_inc, SVF_G, TANH_Q15, at
44.1 kHz), computed from the same formulas, so a desktop render sounds like the FM-1.

  gen_tables.py build/fe_tables.h            the tables themselves (desktop tests, desktop plugins)
  gen_tables.py --shared build/fe_shared.h   a plugin header that uses the host's tables (the FM-1 build)
"""
import argparse
import math
from pathlib import Path

FS = 44100
CTL = 32


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def pitch_oct():
    inc = []
    for p in range(128 * 16):
        f = 440.0 * 2 ** ((p / 16 - 69) / 12)
        inc.append(min(int(f / FS * 2 ** 32), 0x7FFFFFFF))
    top = inc[1856:2048]
    # pitch_inc(p) below must equal the full table: check it
    assert all(inc[q] == top[(q + 64) % 192] >> (10 - (q + 64) // 192) for q in range(2048))
    return top


PITCH_FN = [
    "/* phase increment of pitch p in 1/16 semitone, 0..2047 (MIDI 0..127) */",
    "static inline uint32_t pitch_inc(uint32_t p)",
    "{",
    "    uint32_t i = p + 64u, o = (i * 21846u) >> 22;",
    "    return PITCH_OCT[i - o * 192u] >> (10u - o);",
    "}",
]

STRUCT = [
    "#ifndef FE_TABLES_STRUCT",
    "#define FE_TABLES_STRUCT",
    "struct fe_tables {",
    "    const int16_t *sine;",
    "    const uint32_t *pitch_oct;",
    "    const uint16_t *svf_g;",
    "    const int16_t *tanh_q15;",
    "};",
    "#endif",
]


def full():
    L = arr("SINE", "int16_t", [int(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1025)])
    L += arr("PITCH_OCT", "uint32_t", pitch_oct(), 8) + PITCH_FN
    cut = [30.0 * ((16000 / 30) ** (v / 127)) for v in range(128)]
    L += arr("SVF_G", "uint16_t", [int(4096 * math.tan(math.pi * min(f, 0.45 * FS) / FS)) for f in cut])
    L += arr("TANH_Q15", "int16_t", [int(32767 * math.tanh(i / 256 * 2)) for i in range(257)])
    return L


def shared():
    return STRUCT + [
        "#define FE_SHARED_TABLES 1",
        "static const struct fe_tables *fe_tab;",
        "#define SINE (fe_tab->sine)",
        "#define PITCH_OCT (fe_tab->pitch_oct)",
        "#define SVF_G (fe_tab->svf_g)",
        "#define TANH_Q15 (fe_tab->tanh_q15)",
    ] + PITCH_FN


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("out")
    ap.add_argument("--shared", action="store_true")
    a = ap.parse_args()
    head = ["/* generated by tools/gen_tables.py */", "#pragma once", "#include <stdint.h>",
            f"#define FS {FS}", f"#define CTL {CTL}", ""]
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(head + (shared() if a.shared else full())) + "\n")


if __name__ == "__main__":
    main()

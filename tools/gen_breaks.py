"""The built-in breaks of the JUNGLE engine and its lookup tables -> engines/jungle_data.h

Each break is two bars of sixteenths (32 slices). It is written below as lanes, one per drum, one character a
sixteenth ('x' a hit, '.' none; spaces and '|' are only for reading). A slice of the break is everything that hits
on its sixteenth, so pressing a key plays that sixteenth of the break, the way a sampler plays a chopped break.

The patterns are original arrangements in the styles of the classic funk breaks that jungle, drum & bass and
breakcore are built from. No recording is used: the engine synthesises every hit.

  python3 tools/gen_breaks.py            (writes engines/jungle_data.h)
"""
import math
from pathlib import Path

# the hit bits (engines/eng_jungle.c knows the same)
BITS = {"K": 1, "S": 2, "G": 4, "H": 8, "O": 16, "R": 32, "C": 64}
ACCENT = 128          # set by this script on the eighths: hats and rides are louder there

BREAKS = [
    ("AMEN", {   # the classic jungle break feel: ride on the eighths, the kick pushed, ghost snares between
        "K": "x.x.......xx.... | x.x.......x.....",
        "S": "....x.......x... | ....x.......x...",
        "G": ".......x.x.....x | .......x.x..x..x",
        "R": "x.x.x.x.x.x.x.x. | x.x.x.x.x.x.x...",
        "C": "................ | ..............x.",
    }),
    ("THINK", {  # tight funk: sixteenth hats, an open hat before the bar
        "K": "x.....x...x..... | x.....x..x......",
        "S": "....x.......x... | ....x.......x...",
        "G": "...x.....x....x. | ...x.....x...x.x",
        "H": "xxxxxxxxxxxxxx.x | xxxxxxxxxxxxxx..",
        "O": "..............x. | ..............x.",
    }),
    ("FUNKY", {  # busy funk drummer: kicks on the e's and a's, snares that answer them
        "K": "x.x...x...x..x.. | x.x...x...x..x..",
        "S": "....x.......x... | ....x.......x...",
        "G": ".......x.x.....x | .......x.x..x...",
        "H": "xxxxxx.xxxxxxxxx | xxxxxx.xxxxxxxx.",
        "O": "......x......... | ......x.......x.",
    }),
    ("APACHE", {  # loose, rolling: kick on the 'a', hats on the eighths
        "K": "x..x....x.x..... | x..x....x.x...x.",
        "S": "....x.......x... | ....x.......x...",
        "G": "......x.......x. | ......x....x..x.",
        "H": "x.x.x.x.x.x.x.x. | x.x.x.x.x.x.x...",
        "O": "................ | ..............x.",
    }),
    ("ROLLER", {  # drum & bass two-step: kick on 1 and the '3 and', snare on 2 and 4
        "K": "x.........x..... | x.........x.....",
        "S": "....x.......x... | ....x.......x...",
        "G": ".......x.......x | .......x..x....x",
        "H": "..x...x...x...x. | ..x...x...x...x.",
        "R": "x.x.x.x.x.x.x.x. | x.x.x.x.x.x.x.x.",
    }),
    ("HALF", {   # halftime: one snare a bar, space for the bass
        "K": "x.....x...x..... | x.....x....x....",
        "S": "........x....... | ........x.......",
        "G": "...........x...x | ...........x.x.x",
        "H": "x.x.x.x.x.x.x.x. | x.x.x.x.x.x.x.x.",
        "O": "......x......... | ......x.........",
    }),
    ("ROLLS", {  # breakcore fodder: snare rolls and kick stabs to chop into edits
        "K": "x.x.x.x.x...x... | xxxx....x.x.x.x.",
        "S": "....x...xxxxxxxx | ....xxxx....xxxx",
        "G": "..x...x......... | ................",
        "H": "xxxxxxxxxxxxxxxx | xxxxxxxxxxxxxxxx",
        "C": "x............... | ................",
    }),
    ("RAGGA", {  # dancehall-jungle: the kick on 1 and the 'and' of 2, rimmy ghosts
        "K": "x......x..x..... | x......x..x.....",
        "S": "....x.......x... | ....x.......x.x.",
        "G": "..x..x....x..x.. | ..x..x....x..x..",
        "H": "x.x.x.x.x.x.x.x. | x.x.x.x.x.x.x.x.",
        "O": "...............x | ................",
    }),
]

STEPS = 32


def lanes_to_masks(lanes):
    masks = [0] * STEPS
    for drum, lane in lanes.items():
        cells = lane.replace(" ", "").replace("|", "")
        assert len(cells) == STEPS, (drum, len(cells))
        for i, c in enumerate(cells):
            assert c in ".x", (drum, c)
            if c == "x":
                masks[i] |= BITS[drum]
    for i in range(0, STEPS, 2):
        masks[i] |= ACCENT
    return masks


def table(name, ctype, vals, per=16):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def main():
    L = ["/* generated by tools/gen_breaks.py: do not edit */", "#pragma once", ""]
    L += [f"#define JNG_NBRK {len(BREAKS)}", f"#define JNG_STEPS {STEPS}", ""]
    L += ["/* the breaks: a hit mask per sixteenth (K 1, S 2, G 4, H 8, O 16, R 32, C 64, accent 128) */",
          f"static const uint8_t JNG_BRK[JNG_NBRK][JNG_STEPS] = {{"]
    for name, lanes in BREAKS:
        m = lanes_to_masks(lanes)
        L.append(f"    {{{', '.join(str(v) for v in m)}}},  /* {name} */")
    L += ["};", ""]
    L += ["static const char *const JNG_BRK_NAMES[JNG_NBRK] = {" +
          ", ".join(f'"{n}"' for n, _ in BREAKS) + "};", ""]
    L += ["/* exp(-i / 32), Q15: an envelope a component reads by its time over its time constant */"]
    L += table("JNG_EXP", "int16_t", [int(round(32767 * math.exp(-i / 32))) for i in range(257)])
    L += ["", "/* 2^(st / 12), Q12, st -12 .. +12: the break's speed (a sampler's pitch: faster is higher) */"]
    L += table("JNG_SPD", "uint16_t", [int(round(4096 * 2 ** ((i - 12) / 12))) for i in range(25)], 13)
    out = Path(__file__).resolve().parent.parent / "engines" / "jungle_data.h"
    out.write_text("\n".join(L) + "\n")
    print(out)


if __name__ == "__main__":
    main()

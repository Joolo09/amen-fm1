def main():
    rows = []
    for code in range(32, 127):
        c = chr(code)
        art = G.get(c.upper() if c.isalpha() else c, G["?"] if c not in G else G[c])
        lines = art.split("|")
        assert len(lines) == 7 and all(len(r) == 5 for r in lines), c
        b = [sum(1 << (4 - i) for i, ch in enumerate(r) if ch == "#") for r in lines]
        rows.append("    {" + ", ".join(f"0x{v:02X}" for v in b) + f"}},  /* {c!r} */")
    out = Path(__file__).resolve().parent.parent / "os" / "font.h"
    out.write_text("/* generated by tools/gen_font.py: AMEN OS's 5 x 7 pixel font, ASCII 32..126 */\n"
                   "static const uint8_t FONT[95][7] = {\n" + "\n".join(rows) + "\n};\n")
    print(out)


if __name__ == "__main__":
    main()
